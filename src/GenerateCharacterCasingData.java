
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Locale;
import java.util.function.IntUnaryOperator;

public final class GenerateCharacterCasingData
{
    private static final int MAX_CODE_POINT = Character.MAX_CODE_POINT;

    public static void main(String[] args) throws IOException
    {
        int javaVersion = Runtime.version().feature();

        if (javaVersion != 13)
        {
            throw new IllegalStateException(
                "Expected JDK 13 (Unicode 12.1), but found JDK " + javaVersion);
        }

        Path output = args.length > 0
            ? Path.of(args[0])
            : Path.of("CharacterCasingData.cs");

        int[] lowerCaseMappings = collectMappings(Character::toLowerCase);
        int[] upperCaseMappings = collectMappings(Character::toUpperCase);

        StringBuilder source = new StringBuilder(100_000);

        source.append("// Generated by GenerateCharacterCasingData using JDK 13 (Unicode 12.1).\n")
            .append("// Do not edit manually.\n\n")
            .append("using System.Collections.Generic;\n")
            .append("using NUnit.Framework;\n\n")
            .append("namespace J2N.Tests\n")
            .append("{\n")
            .append("    internal static class CharacterCasingData\n")
            .append("    {\n");

        appendMappings(source, "LowerCaseMappings", lowerCaseMappings);
        appendMappings(source, "UpperCaseMappings", upperCaseMappings);
        appendTestDataProvider(source);

        source.append("    }\n")
            .append("}\n");

        Files.createDirectories(output.toAbsolutePath().getParent());
        Files.writeString(output, source, StandardCharsets.UTF_8);

        System.out.println("Generated: " + output.toAbsolutePath());
        System.out.println("Lowercase mappings: " + lowerCaseMappings.length / 2);
        System.out.println("Uppercase mappings: " + upperCaseMappings.length / 2);
    }

    private static int[] collectMappings(IntUnaryOperator mapping)
    {
        int[] result = new int[4096];
        int length = 0;

        for (int codePoint = 0; codePoint <= MAX_CODE_POINT; codePoint++)
        {
            int mapped = mapping.applyAsInt(codePoint);

            if (mapped != codePoint)
            {
                if (length + 2 > result.length)
                    result = Arrays.copyOf(result, result.length * 2);

                result[length++] = codePoint;
                result[length++] = mapped;
            }
        }

        return Arrays.copyOf(result, length);
    }

    private static void appendMappings(
        StringBuilder source, String name, int[] mappings)
    {
        source.append("        internal static readonly int[] ")
            .append(name)
            .append(" =\n")
            .append("        {\n");

        for (int i = 0; i < mappings.length; i += 2)
        {
            if (i % 8 == 0)
                source.append("            ");

            source.append(String.format(
                Locale.ROOT,
                "0x%06X, 0x%06X",
                mappings[i],
                mappings[i + 1]));

            if (i + 2 < mappings.length)
                source.append(", ");

            if (i % 8 == 6 || i + 2 >= mappings.length)
                source.append('\n');
        }

        source.append("        };\n\n");
    }

    private static void appendTestDataProvider(StringBuilder source)
    {
        source.append(
            "        public static IEnumerable<TestCaseData> AllCodePoints\n" +
            "        {\n" +
            "            get\n" +
            "            {\n" +
            "                for (int codePoint = 0; codePoint <= 0x10FFFF; codePoint++)\n" +
            "                {\n" +
            "                    int expectedLower = GetExpectedMapping(LowerCaseMappings, codePoint);\n" +
            "                    int expectedUpper = GetExpectedMapping(UpperCaseMappings, codePoint);\n" +
            "\n" +
            "                    yield return new TestCaseData(codePoint, expectedLower, expectedUpper);\n" +
            "                }\n" +
            "            }\n" +
            "        }\n\n" +
            "        private static int GetExpectedMapping(int[] mappings, int codePoint)\n" +
            "        {\n" +
            "            int low = 0;\n" +
            "            int high = mappings.Length / 2 - 1;\n" +
            "\n" +
            "            while (low <= high)\n" +
            "            {\n" +
            "                int middle = low + ((high - low) >> 1);\n" +
            "                int key = mappings[middle * 2];\n" +
            "\n" +
            "                if (key == codePoint)\n" +
            "                    return mappings[middle * 2 + 1];\n" +
            "\n" +
            "                if (key < codePoint)\n" +
            "                    low = middle + 1;\n" +
            "                else\n" +
            "                    high = middle - 1;\n" +
            "            }\n" +
            "\n" +
            "            return codePoint;\n" +
            "        }\n");
    }
}
