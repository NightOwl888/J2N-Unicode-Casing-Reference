
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Locale;
import java.util.function.IntUnaryOperator;

public final class GenerateCharacterCasingData
{
    private static final int MAX_CODE_POINT = Character.MAX_CODE_POINT;

    public static void main(String[] args) throws IOException
    {
        int javaVersion = Runtime.version().feature();

        if (javaVersion != 13)
        {
            throw new IllegalStateException(
                "Expected JDK 13 (Unicode 12.1), but found JDK " + javaVersion);
        }

        Path output = args.length > 0
            ? Path.of(args[0])
            : Path.of("CharacterCasingData.cs");

        int[] lowerCaseMappings = collectMappings(Character::toLowerCase);
        int[] upperCaseMappings = collectMappings(Character::toUpperCase);

        StringMappings lowerStringMappings = collectStringMappings(false);
        StringMappings upperStringMappings = collectStringMappings(true);

        int maxStringMappingLength = Math.max(
            lowerStringMappings.maxOutputLength,
            upperStringMappings.maxOutputLength);

        StringBuilder source = new StringBuilder(200_000);

        source.append("// Generated by GenerateCharacterCasingData using JDK 13 (Unicode 12.1).\n")
            .append("// Do not edit manually.\n\n")
            .append("using System;\n\n")
            .append("namespace J2N.Tests\n")
            .append("{\n")
            .append("    internal static class CharacterCasingData\n")
            .append("    {\n")
            .append("        internal const int MaxStringMappingLength = ")
            .append(Math.max(1, maxStringMappingLength))
            .append(";\n\n");

        appendMappings(source, "LowerCaseMappings", lowerCaseMappings);
        appendMappings(source, "UpperCaseMappings", upperCaseMappings);

        appendStringMappings(source, "LowerStringMappings",
            "LowerStringCodePoints", lowerStringMappings);

        appendStringMappings(source, "UpperStringMappings",
            "UpperStringCodePoints", upperStringMappings);

        appendAccessors(source);

        source.append("    }\n")
            .append("}\n");

        Files.createDirectories(output.toAbsolutePath().getParent());
        Files.writeString(output, source, StandardCharsets.UTF_8);

        System.out.println("Generated: " + output.toAbsolutePath());
        System.out.println("Character lowercase mappings: " + lowerCaseMappings.length / 2);
        System.out.println("Character uppercase mappings: " + upperCaseMappings.length / 2);
        System.out.println("String lowercase mappings: " + lowerStringMappings.entries.length / 3);
        System.out.println("String uppercase mappings: " + upperStringMappings.entries.length / 3);
        System.out.println("Maximum string mapping length: " + maxStringMappingLength);
    }

    private static int[] collectMappings(IntUnaryOperator mapping)
    {
        int[] result = new int[4096];
        int length = 0;

        for (int codePoint = 0; codePoint <= MAX_CODE_POINT; codePoint++)
        {
            int mapped = mapping.applyAsInt(codePoint);

            if (mapped != codePoint)
            {
                if (length + 2 > result.length)
                    result = Arrays.copyOf(result, result.length * 2);

                result[length++] = codePoint;
                result[length++] = mapped;
            }
        }

        return Arrays.copyOf(result, length);
    }

    private static StringMappings collectStringMappings(boolean uppercase)
    {
        IntArray entries = new IntArray();
        IntArray outputCodePoints = new IntArray();
        int maxOutputLength = 0;

        for (int codePoint = 0; codePoint <= MAX_CODE_POINT; codePoint++)
        {
            String input = new String(Character.toChars(codePoint));

            String mapped = uppercase
                ? input.toUpperCase(Locale.ROOT)
                : input.toLowerCase(Locale.ROOT);

            int[] mappedCodePoints = mapped.codePoints().toArray();

            // Identity mappings are implicit in the generated data.
            if (mappedCodePoints.length == 1 && mappedCodePoints[0] == codePoint)
                continue;

            entries.add(codePoint);
            entries.add(outputCodePoints.size());
            entries.add(mappedCodePoints.length);

            outputCodePoints.addAll(mappedCodePoints);
            maxOutputLength = Math.max(maxOutputLength, mappedCodePoints.length);
        }

        return new StringMappings(
            entries.toArray(),
            outputCodePoints.toArray(),
            maxOutputLength);
    }

    private static void appendMappings(
        StringBuilder source, String name, int[] mappings)
    {
        source.append("        private static readonly int[] ")
            .append(name)
            .append(" =\n")
            .append("        {\n");

        appendIntValues(source, mappings);

        source.append("        };\n\n");
    }

    private static void appendStringMappings(
        StringBuilder source,
        String entriesName,
        String outputName,
        StringMappings mappings)
    {
        source.append("        private static readonly int[] ")
            .append(entriesName)
            .append(" =\n")
            .append("        {\n");

        appendIntValues(source, mappings.entries);

        source.append("        };\n\n")
            .append("        private static readonly int[] ")
            .append(outputName)
            .append(" =\n")
            .append("        {\n");

        appendIntValues(source, mappings.outputCodePoints);

        source.append("        };\n\n");
    }

    private static void appendIntValues(StringBuilder source, int[] values)
    {
        for (int i = 0; i < values.length; i++)
        {
            if (i % 8 == 0)
                source.append("            ");

            source.append(String.format(Locale.ROOT, "0x%06X", values[i]));

            if (i + 1 < values.length)
                source.append(", ");

            if (i % 8 == 7 || i + 1 == values.length)
                source.append('\n');
        }
    }

    private static void appendAccessors(StringBuilder source)
    {
        source.append(
            "        internal static int GetExpectedLower(int codePoint)\n" +
            "        {\n" +
            "            return GetExpectedMapping(LowerCaseMappings, codePoint);\n" +
            "        }\n\n" +

            "        internal static int GetExpectedUpper(int codePoint)\n" +
            "        {\n" +
            "            return GetExpectedMapping(UpperCaseMappings, codePoint);\n" +
            "        }\n\n" +

            "        internal static int CopyExpectedLowerString(int codePoint, Span<int> destination)\n" +
            "        {\n" +
            "            return CopyExpectedStringMapping(LowerStringMappings, LowerStringCodePoints, codePoint, destination);\n" +
            "        }\n\n" +

            "        internal static int CopyExpectedUpperString(int codePoint, Span<int> destination)\n" +
            "        {\n" +
            "            return CopyExpectedStringMapping(UpperStringMappings, UpperStringCodePoints, codePoint, destination);\n" +
            "        }\n\n" +

            "        private static int GetExpectedMapping(int[] mappings, int codePoint)\n" +
            "        {\n" +
            "            int low = 0;\n" +
            "            int high = mappings.Length / 2 - 1;\n\n" +
            "            while (low <= high)\n" +
            "            {\n" +
            "                int middle = low + ((high - low) >> 1);\n" +
            "                int key = mappings[middle * 2];\n\n" +
            "                if (key == codePoint)\n" +
            "                    return mappings[middle * 2 + 1];\n\n" +
            "                if (key < codePoint)\n" +
            "                    low = middle + 1;\n" +
            "                else\n" +
            "                    high = middle - 1;\n" +
            "            }\n\n" +
            "            return codePoint;\n" +
            "        }\n\n" +

            "        private static int CopyExpectedStringMapping(\n" +
            "            int[] mappings, int[] outputCodePoints, int codePoint, Span<int> destination)\n" +
            "        {\n" +
            "            int low = 0;\n" +
            "            int high = mappings.Length / 3 - 1;\n\n" +
            "            while (low <= high)\n" +
            "            {\n" +
            "                int middle = low + ((high - low) >> 1);\n" +
            "                int entryIndex = middle * 3;\n" +
            "                int key = mappings[entryIndex];\n\n" +
            "                if (key == codePoint)\n" +
            "                {\n" +
            "                    int offset = mappings[entryIndex + 1];\n" +
            "                    int length = mappings[entryIndex + 2];\n\n" +
            "                    if (destination.Length < length)\n" +
            "                        return -1;\n\n" +
            "                    Array.Copy(outputCodePoints, offset, destination.ToArray(), 0, 0);\n" +
            "                    for (int i = 0; i < length; i++)\n" +
            "                        destination[i] = outputCodePoints[offset + i];\n\n" +
            "                    return length;\n" +
            "                }\n\n" +
            "                if (key < codePoint)\n" +
            "                    low = middle + 1;\n" +
            "                else\n" +
            "                    high = middle - 1;\n" +
            "            }\n\n" +
            "            if (destination.IsEmpty)\n" +
            "                return -1;\n\n" +
            "            destination[0] = codePoint;\n" +
            "            return 1;\n" +
            "        }\n");
    }

    private static final class StringMappings
    {
        final int[] entries;
        final int[] outputCodePoints;
        final int maxOutputLength;

        StringMappings(int[] entries, int[] outputCodePoints, int maxOutputLength)
        {
            this.entries = entries;
            this.outputCodePoints = outputCodePoints;
            this.maxOutputLength = maxOutputLength;
        }
    }

    private static final class IntArray
    {
        private int[] values = new int[4096];
        private int length;

        int size()
        {
            return length;
        }

        void add(int value)
        {
            if (length == values.length)
                values = Arrays.copyOf(values, values.length * 2);

            values[length++] = value;
        }

        void addAll(int[] source)
        {
            if (length + source.length > values.length)
            {
                int newLength = values.length;
                while (newLength < length + source.length)
                    newLength *= 2;

                values = Arrays.copyOf(values, newLength);
            }

            System.arraycopy(source, 0, values, length, source.length);
            length += source.length;
        }

        int[] toArray()
        {
            return Arrays.copyOf(values, length);
        }
    }
}
